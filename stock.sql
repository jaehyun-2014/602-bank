create table if not exists public.agora_stocks (
  id uuid primary key default gen_random_uuid(),
  symbol text not null unique,
  name text not null,
  description text not null default '',
  price bigint not null check (price > 0),
  previous_price bigint not null check (previous_price > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.agora_stock_history (
  id bigint generated by default as identity primary key,
  stock_id uuid not null references public.agora_stocks(id) on delete cascade,
  price bigint not null check (price > 0),
  recorded_at timestamptz not null default now()
);

create table if not exists public.agora_stock_holdings (
  account_id uuid not null references public.bank_accounts(id) on delete cascade,
  stock_id uuid not null references public.agora_stocks(id) on delete cascade,
  shares bigint not null default 0 check (shares >= 0),
  avg_buy_price bigint not null default 0 check (avg_buy_price >= 0),
  primary key(account_id,stock_id)
);

create table if not exists public.agora_stock_trades (
  id bigint generated by default as identity primary key,
  account_id uuid not null references public.bank_accounts(id) on delete cascade,
  stock_id uuid not null references public.agora_stocks(id) on delete cascade,
  side text not null check (side in ('buy','sell')),
  shares bigint not null check (shares > 0),
  price bigint not null check (price > 0),
  total bigint not null check (total > 0),
  created_at timestamptz not null default now()
);

alter table public.agora_stocks enable row level security;
alter table public.agora_stock_history enable row level security;
alter table public.agora_stock_holdings enable row level security;
alter table public.agora_stock_trades enable row level security;

revoke all on table public.agora_stocks from anon, authenticated;
revoke all on table public.agora_stock_history from anon, authenticated;
revoke all on table public.agora_stock_holdings from anon, authenticated;
revoke all on table public.agora_stock_trades from anon, authenticated;

