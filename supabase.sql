create extension if not exists pgcrypto with schema extensions;

create table if not exists public.bank_settings (
  key text primary key,
  value text not null
);

create table if not exists public.bank_accounts (
  id uuid primary key default gen_random_uuid(),
  account_no text not null unique,
  name text not null,
  pin_hash text not null,
  balance bigint not null default 0 check (balance >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.bank_transactions (
  id bigint generated by default as identity primary key,
  account_id uuid not null references public.bank_accounts(id) on delete cascade,
  type text not null check (type in ('deposit','withdraw')),
  amount bigint not null check (amount > 0),
  created_at timestamptz not null default now()
);

alter table public.bank_settings enable row level security;
alter table public.bank_accounts enable row level security;
alter table public.bank_transactions enable row level security;

revoke all on table public.bank_settings from anon, authenticated;
revoke all on table public.bank_accounts from anon, authenticated;
revoke all on table public.bank_transactions from anon, authenticated;

