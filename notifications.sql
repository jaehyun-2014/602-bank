create or replace function public.notify_transfer_update()
returns trigger language plpgsql security definer set search_path=''
as $$
declare r public.bank_accounts;
declare s public.bank_accounts;
begin
  if old.status=new.status then return new; end if;
  select * into r from public.bank_accounts where id=new.receiver_account_id;
  select * into s from public.bank_accounts where id=new.sender_account_id;
  if new.status='accepted' then
    perform public.agora_notify(new.sender_account_id,'transfer','송금이 수락되었습니다.',coalesce(r.name,'회원')||'님이 '||new.amount||'공 송금을 받았습니다.','student');
  elsif new.status='rejected' then
    perform public.agora_notify(new.sender_account_id,'transfer','송금이 거절되었습니다.',coalesce(r.name,'회원')||'님이 송금을 거절하여 '||new.amount||'공이 반환되었습니다.','student');
  end if;
  return new;
end;
$$;

drop trigger if exists agora_notify_transfer_update on public.bank_transfers;
create trigger agora_notify_transfer_update after update on public.bank_transfers
for each row execute function public.notify_transfer_update();

