-- 아고라 알림센터
create table if not exists public.agora_notifications (
  id bigint generated by default as identity primary key,
  account_id uuid not null references public.bank_accounts(id) on delete cascade,
  type text not null default 'system',
  title text not null,
  body text not null default '',
  link text not null default 'home',
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists agora_notifications_account_idx
  on public.agora_notifications(account_id,created_at desc);

alter table public.agora_notifications enable row level security;
revoke all on table public.agora_notifications from anon,authenticated;

create or replace function public.agora_notify(
  p_account_id uuid,p_type text,p_title text,p_body text,p_link text default 'home'
)
returns void language plpgsql security definer set search_path=''
as $$
begin
  if p_account_id is null then return; end if;
  insert into public.agora_notifications(account_id,type,title,body,link)
  values(p_account_id,coalesce(p_type,'system'),coalesce(p_title,'아고라 알림'),coalesce(p_body,''),coalesce(p_link,'home'));
end;
$$;

create or replace function public.notify_mail_insert()
returns trigger language plpgsql security definer set search_path=''
as $$
declare s public.bank_accounts;
begin
  select * into s from public.bank_accounts where id=new.sender_account_id;
  perform public.agora_notify(new.recipient_account_id,'mail','새 메일이 도착했습니다.',coalesce(s.name,'회원')||'님이 "'||new.subject||'" 메일을 보냈습니다.','mail');
  return new;
end;
$$;

drop trigger if exists agora_notify_mail on public.agora_mail;
create trigger agora_notify_mail after insert on public.agora_mail
for each row execute function public.notify_mail_insert();

