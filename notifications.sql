drop function if exists public.notification_list(text,text);
create or replace function public.notification_list(p_no text,p_pin text)
returns jsonb language plpgsql security definer set search_path=''
as $$
declare a public.bank_accounts;
begin
 select * into a from public.bank_accounts where account_no=p_no and pin_hash=encode(extensions.digest(p_pin,'sha256'),'hex');
 if not found then raise exception '본인확인에 실패했습니다.'; end if;
 return jsonb_build_object(
  'notifications',coalesce((
   select jsonb_agg(jsonb_build_object(
    'id',n.id,'type',n.type,'title',n.title,'body',n.body,'link',n.link,
    'read_at',n.read_at,'date',to_char(n.created_at at time zone 'Asia/Seoul','YYYY-MM-DD HH24:MI')
   ) order by n.created_at desc)
   from public.agora_notifications n where n.account_id=a.id
  ),'[]'::jsonb)
 );
end;
$$;

drop function if exists public.notification_read(text,text,bigint);
create or replace function public.notification_read(p_no text,p_pin text,p_id bigint)
returns boolean language plpgsql security definer set search_path=''
as $$
declare a public.bank_accounts;
begin
 select * into a from public.bank_accounts where account_no=p_no and pin_hash=encode(extensions.digest(p_pin,'sha256'),'hex');
 if not found then raise exception '본인확인에 실패했습니다.'; end if;
 update public.agora_notifications set read_at=coalesce(read_at,now()) where id=p_id and account_id=a.id;
 return found;
end;
$$;

