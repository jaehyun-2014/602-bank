create table if not exists public.market_items (
  id uuid primary key default gen_random_uuid(),
  seller_account_id uuid not null references public.bank_accounts(id) on delete cascade,
  title text not null,
  description text not null,
  category text not null default '기타',
  price bigint not null check (price >= 0),
  preview_url text not null default '',
  download_url text not null default '',
  created_at timestamptz not null default now(),
  active boolean not null default true
);

create table if not exists public.market_likes (
  item_id uuid not null references public.market_items(id) on delete cascade,
  account_id uuid not null references public.bank_accounts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(item_id,account_id)
);

create table if not exists public.market_cart (
  item_id uuid not null references public.market_items(id) on delete cascade,
  account_id uuid not null references public.bank_accounts(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(item_id,account_id)
);

create table if not exists public.market_purchases (
  id bigint generated by default as identity primary key,
  item_id uuid not null references public.market_items(id) on delete restrict,
  buyer_account_id uuid not null references public.bank_accounts(id) on delete restrict,
  seller_account_id uuid not null references public.bank_accounts(id) on delete restrict,
  price bigint not null check(price >= 0),
  created_at timestamptz not null default now()
);

create index if not exists market_items_category_idx
  on public.market_items(category,created_at desc);
create index if not exists market_purchases_buyer_idx
  on public.market_purchases(buyer_account_id,created_at desc);

alter table public.market_items enable row level security;
alter table public.market_likes enable row level security;
alter table public.market_cart enable row level security;
alter table public.market_purchases enable row level security;

revoke all on table public.market_items from anon, authenticated;
revoke all on table public.market_likes from anon, authenticated;
revoke all on table public.market_cart from anon, authenticated;
revoke all on table public.market_purchases from anon, authenticated;

create or replace function public.market_browse(p_category text default 'all', p_no text default '', p_pin text default '')
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  return jsonb_build_object(
    'items',
    coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id',m.id,
          'title',m.title,
          'description',m.description,
          'category',m.category,
          'price',m.price,
          'preview_url',m.preview_url,
          'download_url',m.download_url,
          'seller_name',a.name,
          'like_count',(select count(*) from public.market_likes l where l.item_id=m.id),
          'liked',exists(select 1 from public.market_likes l2 where l2.item_id=m.id and l2.account_id=(select id from public.bank_accounts where account_no=p_no and pin_hash=encode(extensions.digest(p_pin,'sha256'),'hex') limit 1))
        )
        order by m.created_at desc
      )
      from public.market_items m
      join public.bank_accounts a on a.id=m.seller_account_id
      where m.active=true
        and (p_category='all' or m.category=p_category)
    ),'[]'::jsonb)
  );
end;
$$;

create or replace function public.market_toggle_like(
  p_no text,p_pin text,p_item_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare a public.bank_accounts;
declare exists_like boolean;
begin
  select * into a
  from public.bank_accounts
  where account_no=p_no
    and pin_hash=encode(extensions.digest(p_pin,'sha256'),'hex');

  if not found then raise exception '본인확인에 실패했습니다.'; end if;

  if not exists(select 1 from public.market_items where id=p_item_id and active=true)
    then raise exception '상품을 찾을 수 없습니다.';
  end if;

  select exists(
    select 1 from public.market_likes
    where item_id=p_item_id and account_id=a.id
  ) into exists_like;

  if exists_like then
    delete from public.market_likes where item_id=p_item_id and account_id=a.id;
  else
    insert into public.market_likes(item_id,account_id) values(p_item_id,a.id);
  end if;

  return jsonb_build_object('liked',not exists_like);
end;
$$;

create or replace function public.market_cart_add(
  p_no text,p_pin text,p_item_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare a public.bank_accounts;
declare seller uuid;
begin
  select * into a from public.bank_accounts
  where account_no=p_no
    and pin_hash=encode(extensions.digest(p_pin,'sha256'),'hex');
  if not found then raise exception '본인확인에 실패했습니다.'; end if;

  select seller_account_id into seller
  from public.market_items
  where id=p_item_id and active=true;

  if seller is null then raise exception '상품을 찾을 수 없습니다.'; end if;
  if seller=a.id then raise exception '자신의 상품은 구매할 수 없습니다.'; end if;

  insert into public.market_cart(item_id,account_id)
  values(p_item_id,a.id)
  on conflict(item_id,account_id) do nothing;

  return true;
end;
$$;

