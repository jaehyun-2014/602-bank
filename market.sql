create or replace function public.market_purchase_item(
  p_no text,p_pin text,p_item_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare buyer public.bank_accounts;
declare seller public.bank_accounts;
declare item public.market_items;
begin
  select * into buyer from public.bank_accounts
  where account_no=p_no
    and pin_hash=encode(extensions.digest(p_pin,'sha256'),'hex')
  for update;
  if not found then raise exception '본인확인에 실패했습니다.'; end if;

  select * into item from public.market_items
  where id=p_item_id and active=true
  for update;
  if not found then raise exception '상품을 찾을 수 없습니다.'; end if;

  if item.seller_account_id=buyer.id then
    raise exception '자신의 상품은 구매할 수 없습니다.';
  end if;

  if exists(
    select 1 from public.market_purchases
    where item_id=item.id and buyer_account_id=buyer.id
  ) then
    raise exception '이미 구매한 상품입니다.';
  end if;

  select * into seller
  from public.bank_accounts
  where id=item.seller_account_id
  for update;

  if buyer.balance<item.price then raise exception '잔액이 부족합니다.'; end if;

  update public.bank_accounts set balance=balance-item.price where id=buyer.id;
  update public.bank_accounts set balance=balance+item.price where id=seller.id;

  insert into public.market_purchases(
    item_id,buyer_account_id,seller_account_id,price
  ) values(item.id,buyer.id,seller.id,item.price);

  delete from public.market_cart
  where item_id=item.id and account_id=buyer.id;

  return jsonb_build_object(
    'item_id',item.id,
    'price',item.price,
    'download_url',item.download_url,
    'buyer_balance',buyer.balance-item.price
  );
end;
$$;

create or replace function public.market_purchase_cart(
  p_no text,p_pin text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare buyer public.bank_accounts;
declare c record;
declare total bigint:=0;
begin
  select * into buyer from public.bank_accounts
  where account_no=p_no
    and pin_hash=encode(extensions.digest(p_pin,'sha256'),'hex')
  for update;
  if not found then raise exception '본인확인에 실패했습니다.'; end if;

  for c in
    select m.id,m.seller_account_id,m.price
    from public.market_cart x
    join public.market_items m on m.id=x.item_id
    where x.account_id=buyer.id and m.active=true
    order by x.created_at
  loop
    if c.seller_account_id=buyer.id then continue; end if;
    if exists(select 1 from public.market_purchases where item_id=c.id and buyer_account_id=buyer.id) then continue; end if;
    total:=total+c.price;
  end loop;

  if buyer.balance<total then raise exception '장바구니 전체 금액보다 잔액이 부족합니다.'; end if;

  for c in
    select m.id,m.seller_account_id,m.price
    from public.market_cart x
    join public.market_items m on m.id=x.item_id
    where x.account_id=buyer.id and m.active=true
    order by x.created_at
  loop
    if c.seller_account_id=buyer.id then continue; end if;
    if exists(select 1 from public.market_purchases where item_id=c.id and buyer_account_id=buyer.id) then continue; end if;

    update public.bank_accounts set balance=balance-c.price where id=buyer.id;
    update public.bank_accounts set balance=balance+c.price where id=c.seller_account_id;

    insert into public.market_purchases(item_id,buyer_account_id,seller_account_id,price)
    values(c.id,buyer.id,c.seller_account_id,c.price);

    delete from public.market_cart where item_id=c.id and account_id=buyer.id;
  end loop;

  return jsonb_build_object('total',total,'balance',buyer.balance-total);
end;
$$;

